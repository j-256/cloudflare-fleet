const PACKAGE_ROOT = fileURLToPath(new URL("..", import.meta.url))
const ACCOUNT_PATTERN = /^[a-f0-9]{32}$/i
const DATABASE_PATTERN = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i
const CHECK_TIMEOUT_MS = 30000
const MAX_CONFIGURATION_BYTES = 1024 * 1024
const MAX_MIGRATIONS = 1000
const SUPPORTED_CONFIGURATION_KEYS = new Set(["$schema", "name", "account_id", "main", "compatibility_date", "compatibility_flags", "workers_dev", "preview_urls", "limits", "routes", "build", "assets", "d1_databases", "services", "triggers", "vars", "observability", "secrets", "send_metrics"])
const MIGRATION_TABLE_QUERY = "SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'd1_migrations'"
const MIGRATIONS_QUERY = `SELECT name FROM d1_migrations ORDER BY name LIMIT ${MAX_MIGRATIONS + 1}`

class ReleaseCheckError extends Error {
  constructor(message, code = "precondition") {
    super(message)
    this.name = "ReleaseCheckError"
    this.code = code
  }
}

function requireValue(condition, message, code) {
  if (!condition) throw new ReleaseCheckError(message, code)
}

function httpsOrigin(value) {
  const url = new URL(value)
  requireValue(url.protocol === "https:" && !url.username && !url.password && !url.port
    && url.pathname === "/" && !url.search && !url.hash, "Configuration requires an exact HTTPS origin")
  return url.origin
}

export async function readHostedReleaseConfiguration(file, releaseRoot, environment = {}) {
  let configuration
  try {
    configuration = JSON.parse((await readRegularReleaseFile(file, MAX_CONFIGURATION_BYTES)).content)
  } catch { throw new ReleaseCheckError("Read the JSON configuration generated by hosted configure; comments and custom JSONC require manual review") }
  const c = configuration
  requireValue(c && typeof c === "object" && !Array.isArray(c) && c.vars, "Configuration is incomplete")
  requireValue(Object.keys(c).every((key) => SUPPORTED_CONFIGURATION_KEYS.has(key)), "Custom deployment overrides require manual review")
  requireValue(/^[a-z0-9][a-z0-9-]{0,62}$/.test(c.name || ""), "Worker name is invalid")
  requireValue(ACCOUNT_PATTERN.test(c.vars.FLEET_ACCOUNT_ID || ""), "Account ID is invalid")
  for (const account of [environment.CLOUDFLARE_ACCOUNT_ID, environment.CLOUDFLARE_FLEET_ACCOUNT_ID, c.account_id]) {
    requireValue(!account || account === c.vars.FLEET_ACCOUNT_ID, "Configured account differs from the selected operator account")
  }
  requireValue(Array.isArray(c.routes) && c.routes.length === 1 && c.routes[0].custom_domain === true, "Use one explicit Access-protected custom domain")
  const endpoint = httpsOrigin(`https://${c.routes[0].pattern}`)
  requireValue(new URL(endpoint).hostname === c.routes[0].pattern, "Custom domain must be an exact hostname")
  requireValue(!environment.CLOUDFLARE_FLEET_URL || httpsOrigin(environment.CLOUDFLARE_FLEET_URL) === endpoint, "Hosted endpoint differs from the selected operator endpoint")
  requireValue(c.workers_dev === false && c.preview_urls === false && c.assets?.binding === "ASSETS" && c.assets.run_worker_first === true
    && c.vars.FLEET_LOCAL_DEV === undefined, "Access must cover all requests; disable workers.dev, previews, and local-dev bypass")
  requireValue(/^[a-f0-9]{64}$/i.test(c.vars.ACCESS_AUD || ""), "Access audience is invalid")
  const accessOrigin = httpsOrigin(c.vars.ACCESS_TEAM_DOMAIN)
  requireValue(["true", "false"].includes(c.vars.FLEET_READ_ONLY), "Read/write policy must be explicit")
  requireValue(Array.isArray(c.triggers?.crons) && c.triggers.crons.length === 0, "Fleet must have explicitly empty Cron schedules")
  requireValue(Array.isArray(c.services) && c.services.length === 0, "Service binding overrides require manual review")
  requireValue(Array.isArray(c.d1_databases) && c.d1_databases.length === 1, "Use exactly one Fleet D1 database")
  const database = c.d1_databases[0]
  requireValue(database.binding === "FLEET_DB" && DATABASE_PATTERN.test(database.database_id || "")
    && (!database.migrations_table || database.migrations_table === "d1_migrations")
    && !database.migrations_pattern && !database.preview_database_id, "D1 binding, migration table, or migration selection is unsupported")
  for (const [configured, expected] of [[c.main, "src/hosted/worker.mjs"], [c.assets.directory, ".worker-assets"], [database.migrations_dir, "migrations"]]) {
    requireValue(typeof configured === "string", "Deployment paths are incomplete")
    requireValue(await fs.realpath(path.resolve(path.dirname(file), configured)) === await fs.realpath(path.join(releaseRoot, expected)), "Configuration points outside the selected release; do not deploy an old release through a copied configuration")
  }
  requireValue(c.build?.command === "npm run build:hosted" && !c.build.cwd, "Use the release's standard hosted build command and run Wrangler from the release directory")
  try { normalizeFleetPolicyConfiguration(JSON.parse(c.vars.FLEET_POLICY_JSON)) } catch { throw new ReleaseCheckError("Fleet policy is invalid") }
  return { configuration: c, target: { accountId: c.vars.FLEET_ACCOUNT_ID, worker: c.name, endpoint, accessOrigin,
    databaseId: database.database_id, readOnly: c.vars.FLEET_READ_ONLY === "true" } }
}

async function verifyAssets(root) {
  requireValue(!(await fs.lstat(path.join(root, ".worker-assets"))).isSymbolicLink(), "Hosted asset directory must not be a symbolic link")
  const modules = await collectBrowserModules(path.join(root, "src/app.mjs"), root)
  const files = ["index.html", "styles.css", ...modules.map((file) => path.relative(root, file))]
  for (const file of files) {
    const source = (await readRegularReleaseFile(path.join(root, file))).content
    const destination = path.join(root, ".worker-assets", file)
    requireValue(releaseHash((await readRegularReleaseFile(destination)).content) === releaseHash(source), "Hosted assets differ from the selected release; rerun npm run build:hosted")
  }
  async function walk(relative = "") {
    for (const entry of await fs.readdir(path.join(root, ".worker-assets", relative), { withFileTypes: true })) {
      const name = relative ? `${relative}/${entry.name}` : entry.name
      requireValue(!entry.isSymbolicLink(), "Hosted assets contain a symbolic link")
      if (entry.isDirectory()) await walk(name)
      else requireValue(files.includes(name), "Hosted assets contain an unexpected file")
    }
  }
  await walk()
}

function queryRows(response) {
  const result = response.result
  requireValue(Array.isArray(result) && result.length === 1 && result[0].success === true
    && Array.isArray(result[0].results), "D1 metadata response is incomplete")
  return result[0].results
}

export async function inspectHostedRelease(options = {}) {
  const environment = options.environment || process.env
  const root = options.root || environment.CLOUDFLARE_FLEET_RELEASE_DIR || PACKAGE_ROOT
  const configFile = options.configFile || environment.CLOUDFLARE_FLEET_WRANGLER_CONFIG || path.join(root, "wrangler.jsonc")
  const started = Date.now()
  const signal = options.signal ? AbortSignal.any([options.signal, AbortSignal.timeout(CHECK_TIMEOUT_MS)]) : AbortSignal.timeout(CHECK_TIMEOUT_MS)
  const report = { schemaVersion: 1, requestId: randomUUID(), operation: options.verify ? "verify" : "check", status: "attention", checks: [], release: null, target: null }
  async function check(id, operation) {
    const begin = Date.now()
    try {
      signal.throwIfAborted()
      const value = await operation()
      report.checks.push({ id, status: "pass", elapsedMs: Date.now() - begin })
      return value
    } catch (error) {
      report.checks.push({ id, status: "fail", code: signal.aborted ? "timeout-or-cancelled" : error instanceof ReleaseCheckError ? error.code : "read-failed",
        detail: error instanceof ReleaseCheckError ? error.message : id === "release.integrity" ? "Release integrity or selected version could not be verified; use an unchanged self-hosting archive" : "Read failed or returned unsupported data; check the selected release, configuration, credentials, and permissions",
        httpStatus: Number.isInteger(error?.status) ? error.status : null,
        upstreamRequestId: /^[a-f0-9-]{36}$/i.test(error?.diagnostics?.requestId || "") ? error.diagnostics.requestId : null,
        elapsedMs: Date.now() - begin })
      return null
    }
  }
  const release = await check("release.integrity", () => {
    requireValue(!environment.CLOUDFLARE_FLEET_RELEASE_DIR || path.isAbsolute(environment.CLOUDFLARE_FLEET_RELEASE_DIR), "CLOUDFLARE_FLEET_RELEASE_DIR must be an absolute path")
    requireValue(!environment.CLOUDFLARE_FLEET_WRANGLER_CONFIG || path.isAbsolute(environment.CLOUDFLARE_FLEET_WRANGLER_CONFIG), "CLOUDFLARE_FLEET_WRANGLER_CONFIG must be an absolute path")
    return inspectSelfHostedRelease(root, options.version)
  })
  if (release) {
    const { root: _root, migrations: _migrations, ...identity } = release
    report.release = identity
    await check("release.dependencies", async () => {
      requireValue(Number(process.versions.node.split(".")[0]) >= 22, "Node.js 22 or newer is required", "dependency")
      let installed
      try { installed = JSON.parse(await fs.readFile(path.join(release.root, "node_modules/wrangler/package.json"), "utf8")) } catch { throw new ReleaseCheckError("Install the archive's locked toolchain with npm ci, including development dependencies", "dependency") }
      if (installed.version !== release.wranglerVersion) throw new ReleaseCheckError("Installed Wrangler differs from the release lock; run npm ci", "dependency")
      return true
    })
    await check("release.assets", () => verifyAssets(release.root))
    const configured = await check("configuration", () => readHostedReleaseConfiguration(configFile, release.root, environment))
    if (configured) report.target = configured.target
    if (configured && report.checks.every((entry) => entry.status === "pass") && (options.live || options.verify)) {
      const target = configured.target
      const api = await check("credentials.cloudflare", async () => {
        if (options.api) return options.api
        requireValue(Boolean(environment.CLOUDFLARE_API_TOKEN), "Live preflight requires an account API token with Workers Scripts Read and D1 Read")
        return new CloudflareApi({ accountId: target.accountId, apiToken: environment.CLOUDFLARE_API_TOKEN })
      })
      if (api) {
        await check("deployment", async () => {
          try {
            const response = await api.request(`accounts/${target.accountId}/workers/scripts/${target.worker}/deployments`, { signal })
            report.deployment = activeDeployment(response.result)
            if (options.verify) {
              const serving = report.deployment.versions.filter((version) => version.percentage > 0)
              requireValue(serving.length === 1, "A split deployment cannot establish that the selected release serves all traffic")
              const version = await api.request(`accounts/${target.accountId}/workers/scripts/${target.worker}/versions/${encodeURIComponent(serving[0].id)}`, { signal })
              const bindings = version.result?.resources?.bindings
              requireValue(Array.isArray(bindings), "Serving version bindings are unavailable")
              const databases = bindings.filter((binding) => binding.type === "d1" && binding.name === "FLEET_DB")
              requireValue(databases.length === 1 && databases[0].database_id === target.databaseId, "Serving version uses a different Fleet database")
            }
          } catch (error) {
            if (error.status !== 404 || options.verify || !options.install) throw error
            report.deployment = { status: "not-created" }
          }
          return true
        })
        await check("database.migrations", async () => {
          const query = (sql) => api.request(`accounts/${target.accountId}/d1/database/${target.databaseId}/query`, { method: "POST", body: { sql }, signal })
          const table = queryRows(await query(MIGRATION_TABLE_QUERY))
          requireValue(table.length <= 1 && table.every((row) => row.name === "d1_migrations"), "Migration table coverage is incomplete")
          const rows = table.length ? queryRows(await query(MIGRATIONS_QUERY)) : []
          requireValue(rows.length <= MAX_MIGRATIONS && rows.every((row) => typeof row.name === "string" && row.name.length <= 200 && /^[A-Za-z0-9_.-]+\.sql$/.test(row.name)), "Migration coverage is incomplete")
          const applied = rows.map((row) => row.name)
          const pending = release.migrations.filter((name) => !applied.includes(name))
          const unexpected = applied.filter((name) => !release.migrations.includes(name))
          report.migrations = { pending, unexpected }
          requireValue(pending.length === 0 && unexpected.length === 0, "Migration state differs: back up state and review pending migrations or an older release; no migration was applied")
          return true
        })
      }
      if (options.verify) {
        await check("hosted.identity-and-storage", async () => {
          const remote = options.remote || createRemoteFleetService({ environment: { ...environment,
            CLOUDFLARE_FLEET_BACKEND: "hosted", CLOUDFLARE_FLEET_URL: target.endpoint, CLOUDFLARE_FLEET_ACCOUNT_ID: target.accountId } })
          const status = await remote.status({ signal })
          requireValue(status.storage === "d1" && status.schema === "ready", "Hosted storage is not ready")
          requireValue(status.readOnly === target.readOnly && status.accountId === target.accountId, "Hosted account or read/write policy differs")
          requireValue(status.release?.releaseId === release.releaseId && status.release?.version === release.version
            && status.release?.sourceRevision === release.sourceRevision, "Server release identity differs or is unavailable; the selected release is not verified live")
          report.hosted = { release: { version: status.release.version, releaseId: status.release.releaseId, sourceRevision: status.release.sourceRevision }, storage: status.storage, readOnly: status.readOnly }
          return true
        })
        await check("hosted.access-boundary", async () => {
          const response = await (options.fetchImpl || globalThis.fetch)(`${target.endpoint}/api/commands`, { redirect: "manual", signal })
          const location = response.headers.get("location")
          const redirected = [301, 302, 303, 307, 308].includes(response.status) && location && new URL(location, target.endpoint).origin === target.accessOrigin
          await response.body?.cancel()
          requireValue(response.status === 403 || redirected, "Anonymous API request was not denied or redirected to the configured Access provider")
          return true
        })
      }
    }
  }
  report.status = report.checks.every((entry) => entry.status === "pass") ? "ready" : "attention"
  report.elapsedMs = Date.now() - started
  report.live = options.verify || options.live ? "requested" : "not-requested"
  report.limitations = ["Read-only evidence, not authorization to deploy or migrate", "Checks do not lock out concurrent deployments", "Migration names do not prove schema or data equivalence", "Code rollback does not restore database state"]
  return report
}
